"""Day-grouped validation split of challenge_set (Koopmann-Aziz).

The held-out days are a fixed list of calendar days (UTC day of
actual_offblock_time). They are chosen per month, round(20% of the month's days)
per month, with a seeded generator, so that every season is represented.
The list only contains dates, no labels, and is committed in
koopmann_aziz/splits/val_days_seed<seed>.txt; every experiment reads that file.

    python -m koopmann_aziz.split --seed 0      # (re)writes the committed file
"""
import argparse
import os

import numpy as np
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
DEFAULT_SPLIT = os.path.join(HERE, "splits", "val_days_seed0.txt")


def make_val_days(seed=0, frac=0.2, year=2022):
    rng = np.random.default_rng(seed)
    out = []
    for month in range(1, 13):
        days = pd.date_range(f"{year}-{month:02d}-01", periods=pd.Timestamp(f"{year}-{month:02d}-01").days_in_month)
        k = int(round(frac * len(days)))
        idx = rng.choice(len(days), size=k, replace=False)
        out += [str(days[i].date()) for i in sorted(idx)]
    return sorted(out)


def offblock_day(df):
    """UTC calendar day of actual_offblock_time as 'YYYY-MM-DD' strings"""
    t = pd.to_datetime(df["actual_offblock_time"], utc=True)
    return t.dt.strftime("%Y-%m-%d")


def load_val_days(path=DEFAULT_SPLIT):
    with open(path) as f:
        days = [l.strip() for l in f if l.strip() and not l.startswith("#")]
    assert len(days) == len(set(days)), f"duplicate days in {path}"
    for d in days:
        pd.Timestamp(d)  # raises on malformed dates
    return days


def write_val_days(days, path, seed, frac):
    with open(path, "w", newline="\n") as f:
        f.write(f"# validation days (UTC day of actual_offblock_time), seed={seed}, frac={frac} per month\n")
        f.write(f"# generated by koopmann_aziz/split.py; {len(days)} days\n")
        for d in days:
            f.write(d + "\n")


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--frac", type=float, default=0.2)
    ap.add_argument("--out", default=None)
    a = ap.parse_args()
    out = a.out or os.path.join(HERE, "splits", f"val_days_seed{a.seed}.txt")
    days = make_val_days(a.seed, a.frac)
    write_val_days(days, out, a.seed, a.frac)
    print(f"{len(days)} validation days written to {out}")


if __name__ == "__main__":
    main()
